bool Emptiness( int integer )
{
    if ( integer == 0 )
    {
        return true;
    } else
    {
        return false;
    }


}

bool Nonempty(int integer )
{

    if ( integer == 0 )
    {
        return false;
    } else
    {
        return true ;
    }


}
